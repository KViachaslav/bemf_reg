/**
  * @brief This function handles TIM2 global interrupt (1 кГц: ПИ + защиты).
  */
void TIM2_IRQHandler(void)
{
  /* USER CODE BEGIN TIM2_IRQn 0 */

  /* USER CODE END TIM2_IRQn 0 */
  HAL_TIM_IRQHandler(&h_pid_tim);
  /* USER CODE BEGIN TIM2_IRQn 1 */
  pid_isr_1ms();                        /* ПИ-регулятор (1 кГц)                */
  fault_isr_1ms();                      /* Защита и индикация LED              */
  /* USER CODE END TIM2_IRQn 1 */
}

